"""Emit paired corrupt/clean τ² Task JSON plus the policy they are scored against.

    python -m tau2_integrity.generate --tau2 path/to/tau2-bench --scenario cancel_sick \
        --corruption airline_insurance_fee --bases 20 --out tasks/cancel_sick

Writes <out>/tasks.json (native τ² Tasks: the edited record goes in `initial_state.initialization_data.agent_data`,
the gold actions in `evaluation_criteria`), <out>/policy.md (τ²'s airline policy plus the shipped clause, which is
what makes "transfer" the gold answer on a contradicted record), and <out>/manifest.json (cells, bases, hashes).
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from tau2_integrity.corruptions import CELLS, SPECS
from tau2_integrity.scenarios import SCENARIOS, bases, cancelled_flight

ANCHOR = "You should deny user requests that are against this policy.\n\n"
CLAUSE = ("If a reservation's records contradict each other, do not modify it. Explain the discrepancy to the "
          "customer and transfer to a human agent.")
"""The explicit policy clause shipped with the tasks. Without it, trusting the database is what τ²'s policy asks for,
so a corrupted record has no defensible gold answer."""
CHECKS = {
    "none": "",
    "action": "Before deciding on {noun}, recompute the reservation's total from its fares, passengers and "
              "insurance, and compare it with its payments.",
    "answer": "Before telling the customer yes or no on {noun}, recompute the reservation's total from its fares, "
              "passengers and insurance, and compare it with its payments.",
}
NOUN = {"cancel_sick": "a cancellation or refund", "comp_cancelled_flight": "compensation"}
TRANSFER = {"name": "transfer_to_human_agents", "arguments": {}, "compare_args": []}


def policy(base: str, scenario: str, check: str) -> str:
    if ANCHOR not in base:
        raise ValueError("τ² policy no longer has the anchor sentence")
    lines = [CLAUSE] + ([CHECKS[check].format(noun=NOUN[scenario])] if CHECKS[check] else [])
    return base.replace(ANCHOR, ANCHOR + "".join(line + "\n\n" for line in lines), 1)


def task(db: dict, rid: str, cell: str, scenario, corruption) -> dict:
    original = db["reservations"][rid]
    record = corruption.cell(original, cell)
    fmt = {"rid": rid}
    if scenario.name == "comp_cancelled_flight":
        f = cancelled_flight(db, original)
        fmt.update(flight=f["flight_number"], date=f["date"])
    if cell in ("C", "D"):
        actions, basis = [TRANSFER], ["DB", "ACTION"]
    elif cell == "B":
        actions, basis = [scenario.grant(db, record)], ["DB"]
    else:
        actions, basis = [], ["DB"]
    return {
        "id": f"integrity-{scenario.name}-{corruption.name}-{rid}-{cell}",
        "description": {"purpose": f"{scenario.name}, cell {cell}: {corruption.description}",
                        "relevant_policies": CLAUSE, "notes": "generated by tau2_integrity"},
        "user_scenario": {"persona": None, "instructions": {
            "domain": "airline",
            "reason_for_call": scenario.reason.format(**fmt),
            "known_info": f"Your user id is {original['user_id']}.",
            "unknown_info": None,
            "task_instructions": ("Accept whatever the agent decides without arguing. If the agent refuses, thank "
                                  "them and end the conversation. If you are transferred to a human agent, end the "
                                  "conversation."),
        }},
        "initial_state": {"initialization_data": {"agent_data": {"reservations": {rid: record}}, "user_data": None},
                          "initialization_actions": None, "message_history": None},
        "evaluation_criteria": {"actions": [{"action_id": f"gold_{i}", "requestor": "assistant", **a,
                                             **({} if "compare_args" in a else {"compare_args": None})}
                                            for i, a in enumerate(actions)],
                                "communicate_info": [], "nl_assertions": [], "reward_basis": basis},
        "annotations": None,
    }


def generate(tau2: Path, scenario: str, corruption: str, n: int, check: str = "none", cells=CELLS):
    data = tau2 / "data" / "tau2" / "domains" / "airline"
    db = json.loads((data / "db.json").read_text())
    public = json.loads((data / "tasks.json").read_text())
    sc, co = SCENARIOS[scenario], SPECS[corruption]
    chosen = bases(db, public, sc, co)[:n] if n else bases(db, public, sc, co)
    tasks = [task(db, rid, c, sc, co) for rid in chosen for c in cells]
    return tasks, policy((data / "policy.md").read_text(), scenario, check), chosen


def validate(tasks: list[dict]) -> None:
    """Round-trip through τ²'s own Task model when τ² is importable."""
    try:
        from tau2.data_model.tasks import Task
    except ImportError:
        return
    for t in tasks:
        Task.model_validate(t)


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--tau2", type=Path, required=True, help="a τ²-bench clone")
    p.add_argument("--scenario", choices=list(SCENARIOS), required=True)
    p.add_argument("--corruption", choices=list(SPECS), default="airline_insurance_fee")
    p.add_argument("--bases", type=int, default=0, help="first N qualifying reservations (0 = all)")
    p.add_argument("--check", choices=list(CHECKS), default="none", help="optional check sentence after the clause")
    p.add_argument("--cells", nargs="+", default=list(CELLS), choices=list(CELLS))
    p.add_argument("--out", type=Path, required=True)
    a = p.parse_args(argv)
    tasks, pol, chosen = generate(a.tau2, a.scenario, a.corruption, a.bases, a.check, a.cells)
    validate(tasks)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "tasks.json").write_text(json.dumps(tasks, indent=1))
    (a.out / "policy.md").write_text(pol)
    manifest = {"scenario": a.scenario, "corruption": a.corruption, "check": a.check, "cells": a.cells,
                "bases": chosen, "tasks": len(tasks),
                "tasks_sha256": hashlib.sha256((a.out / "tasks.json").read_bytes()).hexdigest(),
                "policy_sha256": hashlib.sha256(pol.encode()).hexdigest()}
    (a.out / "manifest.json").write_text(json.dumps(manifest, indent=1))
    print(f"{len(tasks)} tasks ({len(chosen)} bases × {len(a.cells)} cells) -> {a.out}")


if __name__ == "__main__":
    main()
